import fs from 'node:fs';
import ContentModel from '../public/content-model.js';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const content=JSON.parse(fs.readFileSync(path.join(root,'content/n5-introduction.v1.json'),'utf8'));
const world=JSON.parse(fs.readFileSync(path.join(root,'public/assets/nihongo-world.json'),'utf8'));
const issues=ContentModel.validate(content,{characterIds:world.characters.map(c=>c.id)}),errors=issues.filter(i=>i.severity==='error');
if(errors.length)throw new Error(errors.map(i=>i.path+': '+i.message).join('\n'));
fs.mkdirSync(path.join(root,'public/lesson-data'),{recursive:true});
fs.writeFileSync(path.join(root,'public/lesson-data/n5-introduction.v1.json'),JSON.stringify(content,null,2)+'\n');
fs.writeFileSync(path.join(root,'public/lesson-content.js'),'/* Generated by scripts/build-lesson.mjs. Edit content/n5-introduction.v1.json. */\n(function(data){if(typeof module===\'object\'&&module.exports)module.exports=data;else window.NP_LESSON_CONTENT=data;})('+JSON.stringify(content)+');\n');
console.log(`Lesson ${content.id} v${content.version}: ${content.questions.length} questions; 3 time plans validated.`);
